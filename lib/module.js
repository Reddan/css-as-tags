import {cssValue} from "./css.js"

export function adapterModule(adapter = "dom") {
  return ["dom", "react", "solid"].includes(adapter) ? `css-as-tags/${adapter}` : adapter
}

export function generateModule(sheet, cssImport, adapter) {
  const value = Object.fromEntries(Array.from(sheet.properties, ([key, name]) => [key, cssValue(sheet, name)]))
  // Computed keys also preserve unusual CSS names such as "__proto__".
  const entries = Object.entries(value).map(([key, text]) => `[${JSON.stringify(key)}]: ${JSON.stringify(text)}`)
  return [
    `import ${JSON.stringify(cssImport)};`,
    `import { createTag as _tag } from ${JSON.stringify(adapterModule(adapter))};`,
    ...Array.from(sheet.components, ([key, name]) => `export const ${key} = /*#__PURE__*/ _tag(${JSON.stringify(name)});`),
    `export default {${entries.join(", ")}};`,
  ].join("\n")
}

// The language server resolves JS symbols against this same declaration shape.
// Keep a map from each declaration name to the corresponding occurrence in CSS.
export function declarations(sheet, adapter) {
  let text = `// Generated by css-as-tags.\nimport type { Tag as _Tag } from ${JSON.stringify(adapterModule(adapter))};\n`
  const positions = new Map()
  function member(prefix, key, suffix, cssName) {
    const start = text.length + prefix.length
    positions.set(start, {name: cssName, length: key.length})
    text += prefix + key + suffix + "\n"
  }
  for (const [key, name] of sheet.components) member("export declare const ", key, ": _Tag;", name)
  text += "declare const styles: {\n"
  for (const [key, name] of sheet.properties) {
    member("  readonly ", JSON.stringify(key), `: ${JSON.stringify(cssValue(sheet, name))};`, name)
  }
  text += "};\nexport default styles;\n"
  return {text, positions}
}
